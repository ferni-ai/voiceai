#!/usr/bin/env npx tsx
/**
 * Writes the layer table in ARCHITECTURE.md from architecture-layers.ts, so the map an agent
 * reads first is the map the architecture gate enforces. One row per layer and per L3
 * context: its purpose, the src/ folders it owns, which of them have an index.ts (a
 * context's public API) and a CLAUDE.md. Only the text between BEGIN and END is generated;
 * everything around it is hand-written.
 *   pnpm docs:map           rewrite the table
 *   pnpm docs:map --check   exit 1 when the table is stale (CI)
 *
 * @module quality/docs-map
 */
import { existsSync, readFileSync, statSync, writeFileSync } from 'fs';
import { dirname, join, resolve } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
import {
  CONTEXTS,
  CONTEXT_PURPOSE,
  LAYER_MAP,
  LAYER_PURPOSE,
  type Context,
} from './architecture-layers.js';

export const BEGIN =
  '<!-- docs:map:begin. Generated by `pnpm docs:map` from architecture-layers.ts; edit that file, not this table. -->';
export const END = '<!-- docs:map:end -->';
const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../../../..');

interface Row {
  name: string;
  purpose: string;
  folders: string[];
}

/** Rows in reading order: entrypoints inward to adapters, then the unassigned bucket. */
export function rowsFrom(
  map: Record<string, string> = LAYER_MAP,
  contexts: readonly Context[] = CONTEXTS
): Row[] {
  const owned = (value: string): string[] =>
    Object.keys(map)
      .filter((k) => map[k] === value)
      .sort();
  const layer = (l: keyof typeof LAYER_PURPOSE, name: string): Row => ({
    name,
    purpose: LAYER_PURPOSE[l],
    folders: owned(l),
  });
  return [
    layer('L5', 'L5'),
    layer('L4', 'L4'),
    ...contexts.map((c) => ({
      name: `L3 ${c}`,
      purpose: CONTEXT_PURPOSE[c],
      folders: owned(`L3:${c}`),
    })),
    layer('L2', 'L2'),
    layer('L1', 'L1'),
    layer('unassigned', 'unassigned'),
  ];
}

const isDir = (path: string): boolean => existsSync(path) && statSync(path).isDirectory();
const short = (path: string): string => path.replace(/^src\//, '');

/** Links to `<folder>/<file>` for each mapped folder that has one (a mapped file is its own entry). */
function links(root: string, folders: string[], file: 'index.ts' | 'CLAUDE.md'): string {
  const found = folders.filter((f) => isDir(join(root, f)) && existsSync(join(root, f, file)));
  return found.length ? found.map((f) => `[\`${short(f)}/\`](${f}/${file})`).join(', ') : 'none';
}

export function renderTable(root: string, rows: Row[] = rowsFrom()): string {
  const lines = [
    '| Layer / context | Purpose | Folders it owns (under `src/`) | index.ts | CLAUDE.md |',
    '|---|---|---|---|---|',
    ...rows.map((r) => {
      const folders = r.folders.map((f) => `\`${short(f)}\``).join(', ') || 'none';
      return `| ${r.name} | ${r.purpose} | ${folders} | ${links(root, r.folders, 'index.ts')} | ${links(root, r.folders, 'CLAUDE.md')} |`;
    }),
  ];
  return lines.join('\n');
}

/** The document with its generated section replaced. Throws when the markers are missing. */
export function splice(doc: string, table: string): string {
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END);
  if (start < 0 || end < start)
    throw new Error(`ARCHITECTURE.md needs the markers:\n${BEGIN}\n${END}`);
  return `${doc.slice(0, start + BEGIN.length)}\n${table}\n${doc.slice(end)}`;
}

/** Returns the exit code: 1 when --check finds the table stale. */
export function run(args: string[]): number {
  const rootAt = args.indexOf('--root');
  const root = rootAt >= 0 && args[rootAt + 1] ? resolve(args[rootAt + 1]!) : REPO_ROOT;
  const file = join(root, 'ARCHITECTURE.md');
  const doc = readFileSync(file, 'utf8');
  const next = splice(doc, renderTable(root));
  if (args.includes('--check')) {
    if (next === doc) return 0;
    process.stderr.write(
      'ARCHITECTURE.md layer table is stale: run `pnpm docs:map` and commit it.\n'
    );
    return 1;
  }
  if (next !== doc) writeFileSync(file, next);
  process.stdout.write(
    next === doc ? 'ARCHITECTURE.md is current.\n' : 'ARCHITECTURE.md layer table rewritten.\n'
  );
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  process.exit(run(process.argv.slice(2)));
