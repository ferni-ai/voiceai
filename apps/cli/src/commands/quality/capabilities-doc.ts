#!/usr/bin/env npx tsx
/**
 * Capability sections: each owner folder's AGENTS.md says which capabilities it owns, which
 * entry callers import and what replaces it, generated from the capability map (decisions.ts)
 * so the doc can't drift from what the decision gate enforces.
 *
 *   pnpm docs:capabilities           write the sections
 *   pnpm docs:capabilities --check   exit 1 when a section is stale, missing or orphaned (CI)
 *
 * The section sits between BEGIN and END in the AGENTS.md beside the capability's entry (its
 * owner module while it has none); text outside the markers is kept. A folder that stops
 * owning a capability loses its section, and the file goes too when nothing else is in it.
 *
 * @module quality/capabilities-doc
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'fs';
import { basename, dirname, join, relative, resolve } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';
import { placementOf } from './architecture-gate.js';
import { walk } from './decision-gate.js';
import { DECISIONS, type DomainDecision } from './decisions.js';

export const BEGIN =
  '<!-- capabilities:begin. Generated by `pnpm docs:capabilities` from apps/cli/src/commands/quality/decisions.ts; edit that file, not this section. -->';
export const END = '<!-- capabilities:end -->';
const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../../../..');

/** The AGENTS.md that describes `d`: beside its public entry, or its owner while it has none. */
export const homeOf = (d: DomainDecision): string =>
  join(dirname(d.entry ?? d.owner.module), 'AGENTS.md');

const cell = (text: string): string => text.replace(/\|/g, '\\|');

function layerOf(file: string): string {
  const p = placementOf(file);
  if (p === null) return 'unassigned';
  return p.context ? `L3 ${p.context}` : p.layer;
}

export function renderSection(ds: readonly DomainDecision[]): string {
  const rows = ds.map((d) => {
    const { owner } = d;
    const until = owner.provisional ? owner.until : '';
    const entry = d.entry === null ? `none yet (${until})` : `\`${d.entry}\``;
    const status = owner.provisional ? `provisional until ${until}: ${d.target}` : 'final';
    const who = `\`${owner.module}#${owner.fn}\` (${layerOf(owner.module)})`;
    return `| ${d.id} | ${cell(d.question)} | ${who} | ${entry} | ${cell(status)} |`;
  });
  return [
    BEGIN,
    '## Capabilities (call the owner through its entry; `pnpm quality:decisions` fails a second owner)',
    '| Capability | Question | Owner | Entry | Status |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    END,
  ].join('\n');
}

/** `doc` with `section` in place of its old one, or appended (a new file is just the section). */
export function splice(doc: string | null, section: string, file: string): string {
  if (doc === null) return `${section}\n`;
  const start = doc.indexOf(BEGIN);
  if (start === -1) return `${doc.trimEnd()}\n\n${section}\n`;
  const end = doc.indexOf(END, start);
  if (end === -1) throw new Error(`${file}: the capabilities section has no end marker`);
  return doc.slice(0, start) + section + doc.slice(end + END.length);
}

/** `doc` without its section; null when nothing else is in it. */
export function unsplice(doc: string): string | null {
  const start = doc.indexOf(BEGIN);
  const end = doc.indexOf(END, start);
  if (start === -1 || end === -1) return doc;
  const rest = `${doc.slice(0, start).trimEnd()}\n${doc.slice(end + END.length).replace(/^\n+/, '\n')}`;
  const kept = rest.trim();
  return kept === '' ? null : `${kept}\n`;
}

const agentsFiles = (root: string): string[] =>
  walk(join(root, 'src'), [])
    .map((p) => relative(root, p))
    .filter((f) => basename(f) === 'AGENTS.md');

/** Each AGENTS.md path → its wanted text (null: delete it), for every home and orphaned section. */
export function plan(
  root: string,
  decisions: readonly DomainDecision[] = DECISIONS,
  existing: readonly string[] = agentsFiles(root)
): Map<string, string | null> {
  const read = (f: string): string | null =>
    existsSync(join(root, f)) ? readFileSync(join(root, f), 'utf8') : null;
  const homes = new Map<string, DomainDecision[]>();
  for (const d of decisions) homes.set(homeOf(d), [...(homes.get(homeOf(d)) ?? []), d]);
  const out = new Map<string, string | null>();
  for (const [f, group] of homes) out.set(f, splice(read(f), renderSection(group), f));
  for (const f of existing) {
    const doc = read(f);
    if (!homes.has(f) && doc !== null && doc.includes(BEGIN)) out.set(f, unsplice(doc));
  }
  return out;
}

/** Returns the exit code: 1 when --check finds a stale, missing or orphaned section. */
export function run(
  args: string[],
  root = REPO_ROOT,
  decisions: readonly DomainDecision[] = DECISIONS
): number {
  const check = args.includes('--check');
  const stale: string[] = [];
  for (const [f, next] of plan(root, decisions)) {
    const path = join(root, f);
    const now = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (now === next) continue;
    stale.push(f);
    if (check) continue;
    if (next === null) rmSync(path);
    else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, next);
    }
  }
  const say = (text: string): boolean => process.stdout.write(`${text}\n`);
  if (check && stale.length > 0) {
    say(`❌ ${stale.length} capabilities section(s) out of date with decisions.ts:`);
    for (const f of stale) say(`  ${f}`);
    say('Fix: pnpm docs:capabilities');
    return 1;
  }
  say(
    check
      ? '✅ Capabilities sections match decisions.ts.'
      : `Wrote ${stale.length} AGENTS.md file(s).`
  );
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exit(run(process.argv.slice(2)));
}
