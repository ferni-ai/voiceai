/**
 * Capability map: each domain decision or capability Ferni has, the one module that owns
 * it, the public entry callers import, and the fingerprints of a second owner.
 *
 * The 2026-10-23 code-health audit (voiceai-evidence/code-health-2026-10-23/ddd.md §2)
 * found these decisions computed in several places each, with different thresholds
 * and vocabularies: 12 crisis deciders, 4 voice resolvers, 14 quiet-hours predicates,
 * 7 forget checkers, 3 tool caps. The decision gate (decision-gate.ts, beside this file)
 * counts fingerprint lines outside each owner in the files a change touches, at the change
 * and at its merge base, and fails when a file gains one. CODEOWNERS asks for a review on
 * this file (it requests, it does not enforce): moving an owner or widening a fingerprint
 * changes the rule for every PR.
 *
 * Every owner is PROVISIONAL: today's best existing module, not the target. `until` names the
 * issue that moves it to `target` (and gives it an index.ts entry where `entry` is null); that
 * PR moves `owner` and `ownerPaths` here and drops `provisional`. `pnpm docs:capabilities`
 * writes each owner folder's AGENTS.md "Capabilities" section from this map; CI fails on drift.
 *
 * A `declarations` fingerprint is the owner's shape: a function, method or function-valued
 * variable declared outside `ownerPaths` whose whole name matches it is a second owner, unless
 * it calls `owner.fn` (a delegate, such as a port adapter).
 *
 * A fingerprint hit is a line of production code under src/ (tests, comments and NOT_DECIDERS excluded)
 * that matches `pattern`, in a file outside `ownerPaths`; with `onlyIn`, only in files whose
 * text matches it; with `in: 'word-lists'`, only inside a regex literal or a string that is
 * an element of an array literal (a word list), not in prose or prompts. Patterns must not
 * use the g or y flag (RegExp.test would keep state between lines; the registry test fails).
 *
 * @module quality/decisions
 */

export interface Fingerprint {
  /** Short name, shown when it fires. */
  readonly name: string;
  readonly pattern: RegExp;
  /** Only files whose whole text matches this count (e.g. Twilio, not Anthropic, messages.create). */
  readonly onlyIn?: RegExp;
  /**
   * 'word-lists': match only regex literals and quoted strings inside array literals.
   * 'declarations': match the whole name of a declared function, method or function value.
   */
  readonly in?: 'word-lists' | 'declarations';
}

export type Owner = { readonly module: string; readonly fn: string } & (
  | { readonly provisional: true; /** the issue that moves it to `target` */ readonly until: `#${number}` }
  | { readonly provisional: false }
);

export interface DomainDecision {
  readonly id: string;
  /** The question, as a caller would ask it. */
  readonly question: string;
  readonly owner: Owner;
  /** The context's index.ts that exports `owner.fn`; null until `owner.until` gives it one. */
  readonly entry: string | null;
  /** Path prefixes where the decision's vocabulary is expected (the owner's own files). */
  readonly ownerPaths: readonly string[];
  /** Where the audit proposes the owner should end up. */
  readonly target: string;
  readonly fingerprints: readonly Fingerprint[];
}

