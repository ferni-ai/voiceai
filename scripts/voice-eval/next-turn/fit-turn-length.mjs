#!/usr/bin/env node
// Fit what TURN_LENGTH=learned and TURN_TEXTURE=learned sample from: how long a friend's next turn
// is, and how often and in what form it is rough, from SBCSAE conversations between friends.
// Held-in conversations only (the held-out third is never read), and the eval moments' own
// replies are left out. Writes aggregate counts only, no corpus text, to
// src/agents/personas/turn-length-table.generated.ts.
//
//   node scripts/voice-eval/next-turn/fit-turn-length.mjs [--moments <moments.json>]
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { parseArgs } from 'node:util';

import { hashSeed } from '../judge-stats.mjs';
import { CONVERSATIONS, turnsOf, words } from './corpus.mjs';

const CORPUS = join(homedir(), 'Documents/voiceai-evidence/human-corpora/sbcsae/raw/SBCSAE');
const OUT = new URL('../../../src/agents/personas/turn-length-table.generated.ts', import.meta.url);
// Buckets, as turn-length.ts reads them: replier's own last turn, the other's turn, energy.
export const OWN = [4, 12]; // 0-4, 5-12, 13+ words
export const THEIRS = [3, 15]; // 1-3, 4-15, 16+
export const ENERGY = [6, 12]; // mean words over the last six turns
export const SIZE = [6, 15]; // the reply itself: 2-6, 7-15, 16+
export const bucket = (x, edges) => edges.filter((e) => x > e).length;

/** Kinds of roughness, as they show in a transcript (the cleaned CHAT line, lowercase). */
const KINDS = {
  opener: /^(?:um+|uh+|well|oh|hm+)\b/, // a sound before the first word
  pause: /.\b(?:um+|uh+)\b/, // a filled pause mid-turn
  restart: /\b(\w+) \1\b|\b\w+- /, // a word said twice, or cut off and restarted
  hedge: /\b(?:you know|i mean|kind of|sort of)\b/,
};

const { values } = parseArgs({ options: { moments: { type: 'string' } } });
const skip = new Set(
  values.moments ? JSON.parse(readFileSync(values.moments, 'utf8')).map((m) => m.id) : []
);
const cells = {};
const texture = SIZE.concat(Infinity).map(() => ({ turns: 0, rough: 0, kinds: {} }));
let n = 0;
for (const file of CONVERSATIONS.filter((f) => hashSeed(f) % 3 !== 0)) {
  const { turns } = turnsOf(readFileSync(join(CORPUS, `${file}.cha`), 'utf8'));
  for (let i = 1; i < turns.length; i++) {
    const [them, me] = [turns[i - 1], turns[i]];
    const size = words(me.text);
    if (them.who === me.who || size < 2 || skip.has(`${file}-${i}`)) continue;
    const own = words(turns.slice(0, i).findLast((t) => t.who === me.who)?.text ?? '');
    const recent = turns.slice(Math.max(0, i - 6), i);
    const energy = recent.reduce((s, t) => s + words(t.text), 0) / recent.length;
    const key = [bucket(own, OWN), bucket(words(them.text), THEIRS), bucket(energy, ENERGY)].join(
      ''
    );
    (cells[key] ??= []).push(Math.min(size, 60));
    const t = texture[bucket(size, SIZE)];
    const found = Object.keys(KINDS).filter((k) => KINDS[k].test(me.text.toLowerCase()));
    t.turns++;
    if (found.length) t.rough++;
    for (const k of found) t.kinds[k] = (t.kinds[k] ?? 0) + 1;
    n++;
  }
}

const deciles = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  return [0.05, 0.15, 0.25, 0.35, 0.45, 0.55, 0.65, 0.75, 0.85, 0.95].map(
    (p) => s[Math.floor(p * s.length)]
  );
};
const all = Object.values(cells).flat();
// A cell with fewer than 60 turns falls back to all turns.
const table = Object.fromEntries(
  Object.entries(cells)
    .sort()
    .map(([k, xs]) => [k, deciles(xs.length >= 60 ? xs : all)])
);
const share = (x, of) => Math.round((100 * x) / of) / 100;
const rough = texture.map((t) => share(t.rough, t.turns));
const kinds = texture.map((t) => {
  const total = Object.values(t.kinds).reduce((a, b) => a + b, 0);
  return Object.fromEntries(Object.keys(KINDS).map((k) => [k, share(t.kinds[k] ?? 0, total)]));
});
writeFileSync(
  OUT,
  `// Generated by scripts/voice-eval/next-turn/fit-turn-length.mjs from ${n} next turns between
// friends in ${CONVERSATIONS.length - CONVERSATIONS.filter((f) => hashSeed(f) % 3 === 0).length} held-in SBCSAE conversations (Du Bois et al. 2000-2005, CC BY-ND).
// Aggregate counts only. Do not edit; re-run the script.

/** A friend's next-turn length in words, 10 quantiles, by [own last turn][their turn][energy] bucket. */
export const NEXT_TURN_WORDS: Record<string, number[]> = ${JSON.stringify(table)};

/** Share of next turns with any roughness, by reply size (2-6, 7-15, 16+ words). */
export const ROUGH_SHARE = ${JSON.stringify(rough)};

/** Which roughness, by reply size: share of all roughness found in turns that size. */
export const ROUGH_KINDS = ${JSON.stringify(kinds)};
`
);
console.log(
  `${n} next turns, ${Object.keys(cells).length} cells; rough by size ${rough}; kinds ${JSON.stringify(kinds)}`
);
