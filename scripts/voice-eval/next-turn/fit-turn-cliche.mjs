#!/usr/bin/env node
// Fit the stock phrases TURN_SPECIFIC=on steers away from: word n-grams (2-4) that Ferni's
// replies use far more than friends' next turns do. Ferni's side: replies generated on held-in
// training moments (never the eval moments); friends' side: every next turn in the held-in SBCSAE
// conversations. Writes phrases only (Ferni's, no corpus text) to
// src/agents/personas/turn-cliche-table.generated.ts.
//
//   node scripts/voice-eval/next-turn/fit-turn-cliche.mjs --ferni <ferni.json>... [--top 120]
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { parseArgs } from 'node:util';

import { hashSeed } from '../judge-stats.mjs';
import { CONVERSATIONS, normalise, turnsOf } from './corpus.mjs';

const CORPUS = join(homedir(), 'Documents/voiceai-evidence/human-corpora/sbcsae/raw/SBCSAE');
const OUT = new URL('../../../src/agents/personas/turn-cliche-table.generated.ts', import.meta.url);

const { values } = parseArgs({
  options: { ferni: { type: 'string', multiple: true }, top: { type: 'string' } },
});
const grams = (text) => {
  const w = normalise(text).split(' ').filter(Boolean);
  const out = new Set();
  for (let n = 2; n <= 4; n++)
    for (let i = 0; i + n <= w.length; i++) out.add(w.slice(i, i + n).join(' '));
  return out;
};
const count = (texts) => {
  const c = new Map();
  for (const t of texts) for (const g of grams(t)) c.set(g, (c.get(g) ?? 0) + 1);
  return c;
};
const ferni = (values.ferni ?? []).flatMap((f) =>
  Object.values(JSON.parse(readFileSync(f, 'utf8'))).map((v) => v.reply)
);
const human = CONVERSATIONS.filter((f) => hashSeed(f) % 3 !== 0).flatMap((f) => {
  const { turns } = turnsOf(readFileSync(join(CORPUS, `${f}.cha`), 'utf8'));
  return turns.filter((t, i) => i > 0 && turns[i - 1].who !== t.who).map((t) => t.text);
});
const [cf, ch] = [count(ferni), count(human)];
// Smoothed log-odds of a phrase in Ferni's replies vs friends' turns, per reply/turn; kept when
// Ferni used it in at least 4 replies and at least 15 times as often as friends do.
const rows = [...cf]
  .filter(([, n]) => n >= 4)
  .map(([g, n]) => {
    const pf = n / ferni.length;
    const ph = ((ch.get(g) ?? 0) + 0.5) / human.length;
    return { g, n, h: ch.get(g) ?? 0, ratio: pf / ph };
  })
  .filter((r) => r.ratio >= 15)
  .sort((a, b) => b.ratio - a.ratio);
// Drop phrases contained in a stronger, longer one already kept.
const kept = [];
for (const r of rows) if (!kept.some((k) => k.g.includes(r.g) || r.g.includes(k.g))) kept.push(r);
const top = kept.slice(0, Number(values.top ?? 120));
writeFileSync(
  OUT,
  `// Generated by scripts/voice-eval/next-turn/fit-turn-cliche.mjs from ${ferni.length} Ferni replies on
// held-in training moments and ${human.length} friends' next turns in held-in SBCSAE conversations
// (Du Bois et al. 2000-2005, CC BY-ND). Ferni's phrases only. Do not edit; re-run the script.

/** Phrases (lowercase, no punctuation) Ferni uses at least 15 times as often as friends do. */
export const STOCK_PHRASES: readonly string[] = ${JSON.stringify(top.map((r) => r.g))};
`
);
console.log(`${ferni.length} Ferni replies, ${human.length} friend turns; ${top.length} phrases`);
console.log(
  top
    .slice(0, 40)
    .map((r) => `${r.g} (${r.n}/${r.h})`)
    .join(' | ')
);
