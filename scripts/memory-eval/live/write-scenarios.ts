#!/usr/bin/env tsx
/**
 * Writes the live memory eval's calls as voice-eval scenarios:
 * scenarios/memlive-<persona>-<n>.txt for each history call and
 * scenarios/memlive-<persona>-quiz.txt for the quiz (with a goodbye that
 * isn't graded). Rerun after editing fixtures/live-personas.ts.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PERSONAS } from '../fixtures/live-personas.js';

const dir = join(import.meta.dirname, '../../voice-eval/scenarios');
const header = (what: string) =>
  `# memory-live: ${what} (generated by scripts/memory-eval/live/write-scenarios.ts)\n`;
for (const p of PERSONAS) {
  p.calls.forEach((lines, i) => {
    writeFileSync(
      join(dir, `memlive-${p.id}-${i + 1}.txt`),
      header(`${p.id} call ${i + 1}`) + lines.join('\n') + '\n'
    );
  });
  const quiz = ["Hey, it's me again.", ...p.quiz.map((q) => q.line), 'Okay, thanks Ferni. Bye!'];
  writeFileSync(
    join(dir, `memlive-${p.id}-quiz.txt`),
    header(`${p.id} quiz`) + quiz.join('\n') + '\n'
  );
}
console.log(`wrote scenarios for ${PERSONAS.map((p) => p.id).join(', ')}`);
