/**
 * The EFFECTIVE_SETTINGS report names every env var src/ reads. This test scans
 * src/ and fails when a read is missing from the generated list. Run it with
 * UPDATE_ENV_READ_NAMES=1 to rewrite the list after adding a read.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { describe, expect, it } from 'vitest';
import { ENV_READ_NAMES } from '../env-read-names.generated.js';

const SRC = join(__dirname, '..', '..');
const GENERATED = join(__dirname, '..', 'env-read-names.generated.ts');
const NAME = '[A-Z][A-Z0-9_]+';

function sourceFiles(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      if (entry !== '__tests__' && entry !== 'node_modules') sourceFiles(path, out);
    } else if (/\.ts$/.test(entry) && !/\.(test|spec|d)\.ts$/.test(entry)) {
      out.push(path);
    }
  }
  return out;
}

// Direct reads: env.X, env['X'] (process.env and an env parameter alike), and a name passed to a helper.
const DIRECT = new RegExp(
  String.raw`(?:\benv(?:\.|\[['"])|\b(?:getEnv|requireEnv|flagOn|envEnabled)\(\s*['"])(${NAME})`,
  'g'
);
// Named reads: env[CONST] where CONST = 'NAME' in the same file.
const INDEXED = /\benv\[([A-Za-z_]\w*)\]/g;
// Local helpers that take an env and a name: positiveIntEnv(env, 'X'), parseEnvNumber('X'), on(env, 'X').
const HELPER_CALL = new RegExp(
  String.raw`\b\w*[Ee]nv\w*\(\s*(?:[^()'"]*,\s*)?['"](${NAME})['"]`,
  'g'
);
const ON_ENV = new RegExp(String.raw`\bon\(\s*env,\s*['"](${NAME})['"]`, 'g');
const CONST = (ident: string) => new RegExp(String.raw`\bconst\s+${ident}\s*=\s*['"](${NAME})['"]`);
// Config objects: envVar: 'NAME' and requiresEnv: ['NAME', ...].
const ENV_VAR = new RegExp(String.raw`\benvVar:\s*['"](${NAME})['"]`, 'g');
const REQUIRES_ENV = /\brequiresEnv:\s*\[([^\]]*)\]/g;
const QUOTED = new RegExp(String.raw`['"](${NAME})['"]`, 'g');

/** Env names read by src/, each with the first place it is read. */
function namesRead(): Map<string, string> {
  const reads = new Map<string, string>();
  const add = (name: string, file: string, index: number, text: string) => {
    if (reads.has(name)) return;
    const line = text.slice(0, index).split('\n').length;
    reads.set(name, `${relative(SRC, file)}:${line}`);
  };
  for (const file of sourceFiles(SRC)) {
    const text = readFileSync(file, 'utf8');
    for (const m of text.matchAll(DIRECT)) add(m[1], file, m.index, text);
    for (const m of text.matchAll(ENV_VAR)) add(m[1], file, m.index, text);
    for (const m of text.matchAll(HELPER_CALL)) add(m[1], file, m.index, text);
    for (const m of text.matchAll(ON_ENV)) add(m[1], file, m.index, text);
    for (const m of text.matchAll(REQUIRES_ENV)) {
      for (const q of m[1].matchAll(QUOTED)) add(q[1], file, m.index, text);
    }
    for (const m of text.matchAll(INDEXED)) {
      const constant = text.match(CONST(m[1]));
      if (constant) add(constant[1], file, m.index, text);
    }
  }
  return reads;
}

const HEADER = `/**
 * Every env var name src/ reads (values are never listed here). Generated by
 * env-read-names.test.ts, for the EFFECTIVE_SETTINGS report (effective-settings.ts),
 * which must name each one even when it is not a manifest flag.
 *
 * Regenerate after adding an env read:
 *   UPDATE_ENV_READ_NAMES=1 pnpm vitest run src/config/__tests__/env-read-names.test.ts
 *
 * The scan covers env.X, env['X'], helper calls (getEnv, requireEnv, flagOn,
 * envEnabled), any call whose name contains "env" with a name literal (positiveIntEnv,
 * parseEnvNumber), on(env, 'X'), env[CONST] for a string constant in the same file,
 * envVar: 'X' and requiresEnv: [...]. It cannot see destructured reads, a helper whose
 * name has no "env" in it, or a name built at run time such as GEMINI_API_KEY_\${i} or
 * \${envPrefix}_CLIENT_SECRET.
 *
 * @module config/env-read-names.generated
 */
export const ENV_READ_NAMES: readonly string[] = \`
`;

function generatedSource(names: string[]): string {
  const lines: string[] = [];
  let line = '';
  for (const name of names) {
    line = line ? `${line} ${name}` : name;
    if (line.length > 96) {
      lines.push(`  ${line}`);
      line = '';
    }
  }
  if (line) lines.push(`  ${line}`);
  return `${HEADER}${lines.join('\n')}\n\`.trim().split(/\\s+/);\n`;
}

describe('env read names', () => {
  it('lists every env name src/ reads', () => {
    const reads = namesRead();
    const names = [...reads.keys()].sort();
    if (process.env.UPDATE_ENV_READ_NAMES === '1') {
      writeFileSync(GENERATED, generatedSource(names));
      return;
    }
    expect(reads.size).toBeGreaterThan(500); // the scanner still finds the reads
    const listed = new Set(ENV_READ_NAMES);
    const missing = [...reads].filter(([name]) => !listed.has(name));
    expect(
      missing.map(([name, where]) => `${name} (${where})`),
      'Regenerate the list: UPDATE_ENV_READ_NAMES=1 pnpm vitest run src/config/__tests__/env-read-names.test.ts'
    ).toEqual([]);
  });

  it('has no duplicate names', () => {
    expect(new Set(ENV_READ_NAMES).size).toBe(ENV_READ_NAMES.length);
  });
});
