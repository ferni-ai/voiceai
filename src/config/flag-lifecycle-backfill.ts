export const FLAG_EXPIRY_BACKFILL: Readonly<
  Record<string, { firstSeen: string; expires: string }>
> = Object.fromEntries(
  GROUPS.flatMap((g) =>
    g.flags
      .split(' ')
      .filter(Boolean)
      .map((name) => [name, { firstSeen: g.firstSeen, expires: g.expires }])
  )
);

/** name → expires, read from this file's text: how the Flag expiry check reads the base version. */
export function parseBackfill(text: string): Map<string, string> {
  const out = new Map<string, string>();
  for (const m of text.matchAll(
    /firstSeen:\s*'[\d-]+',\s*expires:\s*'([\d-]+)',\s*flags:\s*'([^']*)'/g
  )) {
    for (const name of m[2]!.split(' ').filter(Boolean)) out.set(name, m[1]!);
  }
  return out;
}
