/**
 * Writes the two generated lists in src/config, which are gitignored and never
 * committed:
 *
 * - flags/index.generated.ts: one export line per flags/<NAME>.ts. FLAG_MANIFEST
 *   (flag-manifest.ts) reads the flag files through it.
 * - env-read-names.generated.ts: every env var name src/ reads, for the
 *   EFFECTIVE_SETTINGS report (effective-settings.ts).
 *
 * Both used to be committed. Nearly every flag or env-read PR edited them, and
 * GitHub's merge queue ignores the union merge driver, so two PRs adding names in
 * the same spot conflicted and were ejected (#2543, #2489, #2491).
 *
 * Run it with `pnpm gen:lists`. postinstall, typecheck, build, build-fast.ts, dev,
 * the vitest global setup and the worker Dockerfiles run it too.
 *
 * It lives in src/ (not scripts/) so that every image that copies src/ can run it.
 *
 * @module config/generated-lists
 */
import {
  readFileSync,
  readdirSync,
  realpathSync,
  renameSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MIN_ENV_READ_NAMES } from './generated-guard.js';

export const GENERATE_COMMAND = 'pnpm gen:lists';

// ---------------------------------------------------------------------------
// The flag barrel
// ---------------------------------------------------------------------------

export const FLAG_BARREL_HEADER = `/**
 * Every flag file in this directory, one sorted line each. FLAG_MANIFEST
 * (flag-manifest.ts) reads them through this barrel.
 *
 * Generated by src/config/generated-lists.ts and gitignored: never commit or edit
 * it. Typecheck, build, tests and pnpm install regenerate it; by hand run:
 *   ${GENERATE_COMMAND}
 *
 * @module config/flags/index.generated
 */
`;
// Keeps the file a module while no flag has moved here yet.
export const FLAG_BARREL_TAIL = 'export {};\n';
export const FLAG_FILE = /^([A-Z][A-Z0-9_]*)\.ts$/;

/** Flag names in a flags/ directory, from the file names, sorted by code unit. */
export function flagFileNames(flagsDir: string): string[] {
  return readdirSync(flagsDir)
    .map((file) => FLAG_FILE.exec(file)?.[1])
    .filter((name): name is string => name !== undefined)
    .sort();
}

export function flagBarrelSource(names: string[]): string {
  const lines = names.map((name) => `export { ${name} } from './${name}.js';\n`).join('');
  return `${FLAG_BARREL_HEADER}${lines}${FLAG_BARREL_TAIL}`;
}

/** Rewrites flagsDir/index.generated.ts for the flag files in flagsDir. */
export function writeFlagBarrel(flagsDir: string): void {
  writeIfChanged(join(flagsDir, 'index.generated.ts'), flagBarrelSource(flagFileNames(flagsDir)));
}

// ---------------------------------------------------------------------------
// The env-read names
// ---------------------------------------------------------------------------

const NAME = '[A-Z][A-Z0-9_]+';

/** The scanned files: src/**.ts without tests, declarations or __tests__/ helpers. */
export function sourceFiles(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) {
      if (entry !== '__tests__' && entry !== 'node_modules') sourceFiles(path, out);
    } else if (/\.ts$/.test(entry) && !/\.(test|spec|d)\.ts$/.test(entry)) {
      out.push(path);
    }
  }
  return out;
}

// Direct reads: env.X, env['X'] (process.env and an env parameter alike), and a name passed to a helper.
const DIRECT = new RegExp(
  String.raw`(?:\benv(?:\.|\[['"])|\b(?:getEnv|requireEnv|flagOn|envEnabled)\(\s*['"])(${NAME})`,
  'g'
);
// Named reads: env[CONST] where CONST = 'NAME' in the same file.
const INDEXED = /\benv\[([A-Za-z_]\w*)\]/g;
// Local helpers that take an env and a name: positiveIntEnv(env, 'X'), parseEnvNumber('X'), on(env, 'X').
const HELPER_CALL = new RegExp(
  String.raw`\b\w*[Ee]nv\w*\(\s*(?:[^()'"]*,\s*)?['"](${NAME})['"]`,
  'g'
);
const ON_ENV = new RegExp(String.raw`\bon\(\s*env,\s*['"](${NAME})['"]`, 'g');
const CONST = (ident: string) => new RegExp(String.raw`\bconst\s+${ident}\s*=\s*['"](${NAME})['"]`);
// Config objects: envVar: 'X' and requiresEnv: ['X', ...] (one-letter names here keep this file out of the list).
const ENV_VAR = new RegExp(String.raw`\benvVar:\s*['"](${NAME})['"]`, 'g');
const REQUIRES_ENV = /\brequiresEnv:\s*\[([^\]]*)\]/g;
const QUOTED = new RegExp(String.raw`['"](${NAME})['"]`, 'g');

/** Env names read under srcDir, each with the first place it is read. */
export function namesRead(srcDir: string): Map<string, string> {
  const reads = new Map<string, string>();
  const add = (name: string, file: string, index: number, text: string) => {
    if (reads.has(name)) return;
    const line = text.slice(0, index).split('\n').length;
    reads.set(name, `${relative(srcDir, file)}:${line}`);
  };
  for (const file of sourceFiles(srcDir)) {
    const text = readFileSync(file, 'utf8');
    for (const m of text.matchAll(DIRECT)) add(m[1], file, m.index, text);
    for (const m of text.matchAll(ENV_VAR)) add(m[1], file, m.index, text);
    for (const m of text.matchAll(HELPER_CALL)) add(m[1], file, m.index, text);
    for (const m of text.matchAll(ON_ENV)) add(m[1], file, m.index, text);
    for (const m of text.matchAll(REQUIRES_ENV)) {
      for (const q of m[1].matchAll(QUOTED)) add(q[1], file, m.index, text);
    }
    for (const m of text.matchAll(INDEXED)) {
      const constant = text.match(CONST(m[1]));
      if (constant) add(constant[1], file, m.index, text);
    }
  }
  return reads;
}

const ENV_HEADER = `/**
 * Every env var name src/ reads (values are never listed here), for the
 * EFFECTIVE_SETTINGS report (effective-settings.ts), which must name each one even
 * when it is not a manifest flag.
 *
 * Generated by src/config/generated-lists.ts and gitignored: never commit or edit
 * it. Typecheck, build, tests and pnpm install regenerate it; by hand run:
 *   ${GENERATE_COMMAND}
 *
 * The scan covers env.X, env['X'], helper calls (getEnv, requireEnv, flagOn,
 * envEnabled), any call whose name contains "env" with a name literal (positiveIntEnv,
 * parseEnvNumber), on(env, 'X'), env[CONST] for a string constant in the same file,
 * envVar: 'X' and requiresEnv: [...]. It cannot see destructured reads, a helper whose
 * name has no "env" in it, or a name built at run time such as GEMINI_API_KEY_\${i} or
 * \${envPrefix}_CLIENT_SECRET.
 *
 * @module config/env-read-names.generated
 */
export const ENV_READ_NAMES: readonly string[] = \`
`;
const ENV_TAIL = '\n`\n  .trim()\n  .split(/\\s+/);\n';

/** One sorted name per line. */
export function envReadNamesSource(names: string[]): string {
  return `${ENV_HEADER}${names.map((name) => `  ${name}`).join('\n')}${ENV_TAIL}`;
}

/** The sorted env names read under srcDir. Throws when the scan finds too few. */
export function envReadNames(srcDir: string): string[] {
  const names = [...namesRead(srcDir).keys()].sort();
  if (names.length < MIN_ENV_READ_NAMES) {
    throw new Error(
      `generated-lists: found ${names.length} env reads under ${srcDir}, expected at least ` +
        `${MIN_ENV_READ_NAMES}. Is that the repo's src/?`
    );
  }
  return names;
}

// ---------------------------------------------------------------------------
// Writing
// ---------------------------------------------------------------------------

/**
 * Writes only when the content changed (so vitest watch does not loop), through a
 * rename, so a parallel run (vitest shards in one checkout) never reads half a file.
 */
function writeIfChanged(path: string, text: string): boolean {
  try {
    if (readFileSync(path, 'utf8') === text) return false;
  } catch {
    // Absent: write it.
  }
  const tmp = `${path}.${process.pid}.tmp`;
  writeFileSync(tmp, text);
  renameSync(tmp, path);
  return true;
}

/** The two generated files for the repo at root, as path -> source. */
export function generatedLists(root: string): Map<string, string> {
  const config = join(root, 'src', 'config');
  const flags = join(config, 'flags');
  return new Map([
    [join(flags, 'index.generated.ts'), flagBarrelSource(flagFileNames(flags))],
    [
      join(config, 'env-read-names.generated.ts'),
      envReadNamesSource(envReadNames(join(root, 'src'))),
    ],
  ]);
}

/** Writes both generated files for the repo at root; returns the ones that changed. */
export function writeGeneratedLists(root: string): string[] {
  return [...generatedLists(root)]
    .filter(([path, text]) => writeIfChanged(path, text))
    .map(([p]) => p);
}

/** The repo root, from this file's place in src/config/. */
export const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

function isMain(): boolean {
  try {
    return realpathSync(process.argv[1] ?? '') === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}
if (isMain()) {
  const changed = writeGeneratedLists(REPO_ROOT);
  const note = changed.length
    ? `wrote ${changed.map((p) => relative(REPO_ROOT, p)).join(', ')}`
    : 'up to date';
  process.stdout.write(`gen:lists: ${note}\n`);
}
