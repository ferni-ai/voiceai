/**
 * phrase-loops-safety.generated.ts holds every line of wording in the crisis
 * and safety scripts, so PHRASE_LOOP_GUARD never tells Ferni to stop saying
 * one (phrase-loops.ts). This test fails when a script changes and the list
 * wasn't regenerated: UPDATE_SAFETY_WORDING=1 rewrites it (then run prettier).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import ts from 'typescript';
import { describe, expect, it } from 'vitest';
import { SAFETY_WORDING } from '../phrase-loops-safety.generated.js';

const ROOT = join(__dirname, '..', '..', '..', '..');
/** The scripts and guidance a crisis or safety turn speaks or is asked to say. */
const SAFETY_SOURCES = [
  'src/services/safety/crisis-response.ts',
  'src/services/safety/crisis-guard.ts',
  'src/services/safety/crisis-grounded-screen.ts',
  'src/services/safety/crisis-agreement.ts',
  'src/services/safety/crisis-grounded-release.ts',
];

/** Every string literal's lines of three or more words, in source order, once each. */
function wordingIn(files: readonly string[]): string[] {
  const lines: string[] = [];
  const add = (text: string): void => {
    for (const line of text.split('\n')) {
      const kept = line.replace(/\s+/g, ' ').trim();
      if ((kept.match(/[A-Za-z']+/g) ?? []).length >= 3 && !lines.includes(kept)) lines.push(kept);
    }
  };
  for (const file of files) {
    const path = join(ROOT, file);
    const source = ts.createSourceFile(path, readFileSync(path, 'utf8'), ts.ScriptTarget.Latest);
    const visit = (node: ts.Node): void => {
      if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) add(node.text);
      else if (ts.isTemplateExpression(node)) {
        add(node.head.text);
        node.templateSpans.forEach((span) => add(span.literal.text));
      }
      ts.forEachChild(node, visit);
    };
    visit(source);
  }
  return lines;
}

describe('safety wording list', () => {
  it('is every line of the crisis and safety scripts', () => {
    const wording = wordingIn(SAFETY_SOURCES);
    if (process.env.UPDATE_SAFETY_WORDING === '1') {
      writeFileSync(
        join(__dirname, '..', 'phrase-loops-safety.generated.ts'),
        `/**\n * Every line of wording in the crisis and safety scripts (${SAFETY_SOURCES.length} files), which\n * PHRASE_LOOP_GUARD never names (phrase-loops.ts). Generated by\n * __tests__/phrase-loops-safety.test.ts: UPDATE_SAFETY_WORDING=1 rewrites it.\n */\nexport const SAFETY_WORDING: readonly string[] = ${JSON.stringify(wording, null, 2)};\n`
      );
      return;
    }
    expect(
      SAFETY_WORDING,
      'Regenerate: UPDATE_SAFETY_WORDING=1 npx vitest run <this file>'
    ).toEqual(wording);
    // The lines the round-1 verify found named in a note are on the list.
    for (const line of [
      'Are you somewhere safe right now?',
      "2. Once, gently, say you're really glad they're talking with you, and that if things ever get heavy they can call or text 988, any time",
    ])
      expect(SAFETY_WORDING).toContain(line);
  });
});
